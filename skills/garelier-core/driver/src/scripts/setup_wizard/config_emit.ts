// W-083 ts-first: fresh-mode setup_config.toml generation.
//
// Faithful port of the setup_config.toml heredoc block in setup_wizard.ts
// (lines 2773-3252). Returns the file body WITHOUT the trailing [setup]
// completion marker (that is appended separately, matching the bash `>>`).

import { type WizardPaths } from "./paths.ts";
import { frameworkVersion } from "../../version.ts";

export interface ConfigEmitInput {
  ctx: WizardPaths;
  projectName: string;
  now: string;
  pmId: string;
  target: string;
  targetSlug: string;
  studioBranch: string;
  pmDir: string;
  qgCmds: string[];
  stack: string;
  permissionProfile: string;
  obsPolicyEnabled: boolean;
  grdPolicyEnabled: boolean;
  conPolicyEnabled: boolean;
}

export function emitFreshSetupConfig(inp: ConfigEmitInput): string {
  const L: string[] = [];
  const p = (s: string): void => {
    L.push(s);
  };
  p("# Garelier setup configuration");
  p(`# Generated by setup_wizard.ts on ${inp.now}`);
  p("#");
  p("# Add or remove agents by re-running setup_wizard.ts in --mode diff");
  p(`# from inside ${inp.pmDir}/.`);
  p("# To enable health check warnings, uncomment the [health_check] section");
  p("# at the bottom and adjust thresholds.");
  p("");
  p("[project]");
  p(`name = "${inp.projectName}"`);
  p(`initialized_at = "${inp.now}"`);
  p(`garelier_version = "${frameworkVersion()}"`);
  p("");
  p("[pm]");
  p(`pm_id = "${inp.pmId}"`);
  p("");
  p("[branches]");
  p(`target = "${inp.target}"`);
  p(`target_slug = "${inp.targetSlug}"`);
  p(`integration = "${inp.studioBranch}"`);
  p("");
  p("# PM and Dock provider/model stay unset unless explicitly configured.");
  p("# Role routing is task authority: dispatch --provider / --model / --effort,");
  p("# then blueprint");
  p("# hints, then [model_routing] policy. Role metadata never selects a provider.");
  p("[runner]");
  p("# pm_provider / pm_model / pm_effort");
  p("# dock_provider / dock_model / dock_effort");
  p("# are intentionally absent: no provider/model default is selected.");
  p('# pm_effort = "xhigh"');
  p('# dock_effort = "xhigh"');
  p("");
  p("# Every role capability is available without a fixed roster. Dispatch creates");
  p("# an ephemeral role home and derives its identity from the task. Persistent");
  p("# role-container metadata, when intentionally maintained by diff mode, is");
  p("# operational inventory only and has no provider/model/effort authority.");
  p("");
  p("# === Optional project-declared dispatch environment ===");
  p("# [[dispatch.env]] is provider- and stack-neutral; declarations expand per selected child.");
  p("# Allowed placeholders: {checkout}, {project}, {container}, {dispatch_id}, {role}, {slug}.");
  p("# `why` is required; applies_to defaults to [\"producer\"]. Unknown placeholders, missing why,");
  p("# and empty expansion after values are established fail prepare. A not-yet-established placeholder is reported as skipped.");
  p("# Core-owned env wins collisions. Never put secrets in tracked config.");
  p("# [[dispatch.env]]");
  p('# name = "PROJECT_CHECKOUT"');
  p('# value = "{checkout}"');
  p('# why = "Explain why this consumer project needs the value"');
  p('# applies_to = ["producer", "gate"]');
  p("");
  p("[milestones]");
  p("current = []");
  p("");
  p("# === Lens defaults (focus only; never authority) ===");
  p("#");
  p("# A Lens Group tunes judgment focus for a role. It cannot change");
  p("# permissions, write paths, MUST BLOCK conditions, or handoff format.");
  p("# PM may override per blueprint in '## Lens selection'.");
  p("[lenses.defaults]");
  p('pm = "pm.planning:delivery_balanced"');
  p('dock = "dock.dispatch:balanced"');
  p('worker = "worker.implementation:reuse_first"');
  p('scout = "scout.investigation:source_first"');
  p('smith = "smith.integration:adversarial_personas"');
  p('librarian = "librarian.source:strict"');
  p('guardian = "guardian.risk_control:strict"');
  p('observer = "observer.review:over_engineering"');
  p('concierge = "concierge.external_ops:explicit_only"');
  p('artisan = "artisan.creation:reuse_first"');
  p('wanderer = "wanderer.dialogue:sdd"');
  p("");
  p("# === Status Web Console (read-only) ===");
  p("#");
  p("# A local, read-only browser view of Garelier state (routes, roles,");
  p("# branches, merge gate, recent reports, warnings, source/routine");
  p("# registries). Zero AI tokens — it only reads runtime files. Start it");
  p("# with `bun run status -- --pm-id <pm_id>` from the driver directory.");
  p("# It binds to loopback only and never mutates state.");
  p("[status_web]");
  p("enabled = false              # informational; the standalone command runs regardless");
  p('host = "127.0.0.1"           # loopback only; non-loopback values are rejected');
  p("port = 3787");
  p("auto_refresh_seconds = 5");
  p("read_only = true             # phase 1 is read-only; no operation UI");
  p("show_source_urls = true      # false => show only the host of source registry URLs");
  p("");
  p("# === Retention (high-volume operation) ===");
  p("#");
  p("# Defaults from garelier-core/retention.md. Tune when daily reports,");
  p("# Scout inspections, or runtime archives become high-volume.");
  p("[retention]");
  p('inspection_path_granularity = "month"');
  p("inspection_monthly_summary = true");
  p("runtime_archive_keep_days = 30");
  p("runtime_archive_keep_files = 300");
  p("role_local_archive_keep_days = 30");
  p("# runtime/merge_gate/archive/ is retained by [merge_gate]");
  p("# archive_keep_days (default 14, W-038) instead of this block —");
  p("# see garelier-core/retention.md.");
  p("");
  p("# === Adaptive dispatch admission (W-330) ===");
  p("#");
  p("# Garelier has no fixed concurrent-agent cap. Admit each task from advertised");
  p("# provider/substrate availability plus current host CPU/memory/I/O pressure and");
  p("# task resource_class. A host slot quota (for example a provider account's current");
  p("# four total slots) is external availability, never a framework default.");
  p("#");
  p("# Keep tiers only as priority guidance; do not add max_concurrent_agents.");
  p("[concurrency]");
  p('tiers = [["concierge", "guardian", "observer"], ["smith", "librarian"], ["worker", "scout", "artisan"], []]');
  p("starvation_cycles = 3");
  p("");
  p("# === Output control (DEC-028) ===");
  p("#");
  p("# Keeps provider FINAL responses short and driver logs from bloating, on top");
  p("# of compact-handoff + retention. Over-budget responses are WARNED, not failed.");
  p("# Never shortens code/paths/commands/URLs/errors/SHAs, never hides risks.");
  p("[output_control]");
  p("enabled = true");
  p('default_profile = "compact"          # normal | compact | micro');
  p('violation_mode = "warn"              # warn (observe) | fail (experimental)');
  p("model_result_log_chars = 600         # excerpt cap in driver JSONL (100-5000)");
  p("error_tail_chars = 500");
  p("driver_log_max_bytes = 10485760      # rotate JSONL past this size");
  p("driver_log_keep_files = 10");
  p("usage_summary = true                 # runtime/driver/usage/YYYY-MM.jsonl");
  p("");
  p("[output_control.profiles.normal]");
  p("soft_result_chars = 1600");
  p("max_bullets = 8");
  p("[output_control.profiles.compact]");
  p("soft_result_chars = 900");
  p("max_bullets = 5");
  p("[output_control.profiles.micro]");
  p("soft_result_chars = 500");
  p("max_bullets = 3");
  p("");
  p("# guardian/concierge stay normal so warnings/approvals are not pressured short.");
  p("[output_control.roles]");
  p('pm = "normal"');
  p('dock = "compact"');
  p('worker = "compact"');
  p('smith = "compact"');
  p('artisan = "compact"');
  p('scout = "micro"');
  p('observer = "micro"');
  p('librarian = "compact"');
  p('guardian = "normal"');
  p('concierge = "normal"');
  p("");
  p("# === Optional: Health check ===");
  p("#");
  p("# Uncomment to enable. PM will perform a stale-state scan when the");
  p("# user explicitly invokes a health check (garelier-pm/references/health-and-bundles.md §14).");
  p("# Thresholds are in hours. Omit any threshold to disable that check.");
  p("#");
  p("# [health_check]");
  p("# worker_working_warn_hours = 24");
  p("# worker_blocked_warn_hours = 12");
  p("# scout_working_warn_hours = 12");
  p("# scout_reporting_warn_hours = 6");
  p("# dock_silent_warn_hours = 24");
  p("# pending_backlog_warn_hours = 48");
  p("");
  p("# === Optional: Autonomous dispatch loop ===");
  p("#");
  p("# Garelier can self-pace toward a goal on large, long-running roadmaps");
  p("# (dispatch-only, DEC-061/066: the attended PM/Dock session arms a");
  p("# self-paced /loop; roles run as in-session subagents / `codex exec`).");
  p("# The top-level switch is `enabled`. When false (default), Garelier behaves");
  p("# as a classic setup with all user-confirmation gates intact; one-off");
  p("# dispatches need no [autonomy] at all.");
  p("#");
  p("# When enabled = true:");
  p("#   - PM skips blueprint-drafting and milestone confirmation per the");
  p("#     auto_approve_* flags below");
  p("#   - each tick runs DISPATCH -> GATE (Guardian -> Observer) -> INTEGRATE ->");
  p("#     RECORD; the [jig] block above (DEC-062, default-on) executes the tick");
  p("#     as code, and the four HARD human-decision gates always park to PM");
  p("#     (see garelier-pm/references/autonomous-mode.md)");
  p("#");
  p("# Promote flow (studio -> target merge) ALWAYS requires explicit user");
  p("# instruction, even when the loop is armed. PM records the approval and");
  p("# Concierge executes it; there is no PM fallback and no auto_promote flag.");
  p("#");
  p("# [autonomy]");
  p("# enabled = false                          # arm the self-paced /loop (opt-in)");
  p("# auto_approve_blueprints = false          # PM auto-proceeds on its own judgment (soft-gate collapse)");
  p("# auto_approve_milestones = false          # milestone bookkeeping commits without confirmation");
  p("#");
  p("# No fan_out_cap: tick admission uses current provider/host/resource telemetry.");
  p("# # (require_for_all_merges is NOT an [autonomy] key — it lives in");
  p("# #  [guardian_policy] / [observer_policy] above; keep it true there.)");
  p("# protected_paths = [                      # HARD gates to the human PM (engine-core/protected)");
  p('#   "src/core/**", "<dependency-manifest>", "<lockfile>", ".github/**", "infra/**", "deploy/**", "migrations/**",');
  p("# ]");
  p("");
  p("# === Quality gate (DEC-007) ===");
  p("#");
  p("# Commands run by the merge-gate subprocess after");
  p("# 'git merge --no-ff --no-commit'. Each is a single shell line.");
  p("# Failure of any aborts the merge. The subprocess runs in the");
  p("# background relative to the dispatch tick, so other dispatched");
  p("# roles continue in parallel during the merge.");
  p("#");
  p("# Garelier targets any large app, not just Rust. 'stack' picks a");
  p("# default command set; 'commands' overrides it (explicit wins).");
  p("[quality_gate]");
  p(`stack = "${inp.stack}"`);
  p("commands = [");
  for (const c of inp.qgCmds) p(`    "${c}",`);
  p("]");
  p("timeout_minutes_per_cmd = 120");
  p("");
  p("# Worker-authored register policy is deliberately project-owned.");
  p("# gate_runner --from-register fails closed until the project declares");
  p("# [quality_gate.register] steps, terminal closure, touched-path coverage,");
  p("# optional project-owned argv order checks, same-run step supersessions,");
  p("# typed summary metrics, run-summary patterns, and test-tree marker/root");
  p("# inventory. Supersession never carries prior GREEN evidence. See the");
  p("# canonical setup_config.toml template for the language-neutral schema.");
  p("");
  p("# === Standing prompt constraints (W-191) ===");
  p("#");
  p("# Per-project rules dispatch_prepare bundles into EVERY role preamble so");
  p("# the PM never restates them per dispatch (the PM prompt shrinks to a row");
  p("# pointer + this dispatch's ruling). One quoted string per constraint.");
  p("[prompt]");
  p("standing = [");
  p("    # \"fixed-point arithmetic only in sim hot paths — no f32 in canonical state\",");
  p("    # \"renormalize text to LF before commit (repo eol=lf)\",");
  p("]");
  p("");
  p("# === Permissions (autonomy profile) ===");
  p("#");
  if (inp.permissionProfile === "") {
    p("# No [permissions] table was generated. Setup does not persist or");
    p("# change the user's provider permissions.");
  } else {
    p("# Explicit advanced override requested by the user.");
    p("[permissions]");
    p(`profile = "${inp.permissionProfile}"`);
    p("allow_network = false");
    p("allow_destructive_commands = false");
    p("allow_secret_read = false");
    p('require_pm_approval_paths = [".env*", "infra/**", "migrations/**", ".github/workflows/**", "deploy/**"]');
    p('forbidden_paths = ["**/*.pem", "**/*secret*", "**/id_rsa"]');
  }
  p("");
  p("# === Observer policy (DEC-019) ===");
  p("#");
  p("# Observer is a framework capability selected per task. This policy");
  p("# keeps independent review enabled without requiring a fixed roster.");
  p("[observer_policy]");
  p(`enabled = ${inp.obsPolicyEnabled}`);
  p("require_for_all_merges = true         # review EVERY merge (worker->guardian->observer->dock); false = review only on the triggers below");
  p("require_for_artisan_premerge = true");
  p("require_for_large_diff = true");
  p("large_diff_lines = 800");
  p("require_for_protected_paths = true");
  p("require_for_public_api_change = true");
  p("require_for_migration = true");
  p("require_for_auth_security = true");
  p("allow_worker_direction_request = true");
  p("max_parallel_requests = 1");
  p("advice_is_binding = false");
  p("");
  p("# === Guardian policy (DEC-024) ===");
  p("#");
  p("# Guardian is the security GATE: commit-free, on an ephemeral `gavel`");
  p("# branch, reads Librarian-owned security knowledge");
  p("# (the knowledge security/ tree) and emits PASS / PASS_WITH_NOTES / BLOCK /");
  p("# NO_OPINION. Guardian is available without a fixed roster.");
  p("[guardian_policy]");
  p(`enabled = ${inp.grdPolicyEnabled}`);
  p("require_for_all_merges = true         # security-gate EVERY merge (guardian step of worker->guardian->observer->dock); false = gate only on the mechanical triggers below");
  p('branch_namespace = "gavel"');
  p("# Gate timings (delta is the core; preflight/final are staged).");
  p("require_delta_before_observer = true");
  p("require_final_before_merge = true");
  p("require_for_artisan_premerge = true");
  p("require_for_promote = true");
  p("# Mechanical triggers (when a gate is mandatory).");
  p("require_for_dependency_changes = true");
  p("require_for_lockfile_changes = true");
  p("require_for_auth_security = true");
  p("require_for_config_infra_ci_deploy = true");
  p("require_for_protected_paths = true");
  p("# Blocking rules.");
  p("block_on_secret = true");
  p("block_on_pii = true");
  p("block_on_customer_data = true");
  p("block_on_private_key = true");
  p("block_on_critical_vulnerability = true");
  p("block_on_high_vulnerability = true");
  p("block_on_forbidden_license = true");
  p("block_on_unknown_license = false");
  p("block_when_required_scanner_unavailable = true");
  p("# Output safety.");
  p("redact_evidence = true");
  p("forbid_secret_value_in_report = true");
  p("");
  p("[guardian_policy.security_sensitive_paths]");
  p('paths = [".env*", "**/*.pem", "**/*.key", "**/*secret*", "**/*credential*", "infra/**", "deploy/**", ".github/workflows/**", "migrations/**"]');
  p("");
  p("[guardian_policy.package_files]");
  p('paths = ["package.json", "package-lock.json", "pnpm-lock.yaml", "yarn.lock", "Cargo.toml", "Cargo.lock", "requirements.txt", "pyproject.toml", "poetry.lock", "go.mod", "go.sum"]');
  p("");
  p("# Scanner commands. Empty = Guardian uses available project tools and");
  p("# reports NO_OPINION/BLOCK per policy if a required command is missing.");
  p("# If gitleaks cannot be used, PM may set:");
  p("#   block_when_required_scanner_unavailable = false");
  p('#   secret_scan = "off"');
  p("# Guardian then runs in degraded mode and must report that scanner coverage");
  p("# was intentionally disabled; it must not claim full secret-scanner coverage.");
  p("[guardian_tools]");
  p('secret_scan = "gitleaks dir . --no-banner --redact --report-format json --report-path -"');
  p('pii_scan = ""');
  p('dependency_scan = ""');
  p('license_scan = ""');
  p('sast_scan = ""');
  p("");
  p("# === Concierge policy (external operations executor, DEC-025) ===");
  p("#");
  p("# Concierge EXECUTES PM-approved operations that leave Garelier's local");
  p("# sandbox (Phase 1: promote_target + read-only sync_remote). Reads");
  p("# Librarian-owned external_operations/ and consumes the");
  p("# Guardian promote_gate verdict. The role is available without a fixed");
  p("# identity. Enabling does NOT auto-push — external writes");
  p("# still require an explicit user instruction behind the PM assignment.");
  p("[concierge_policy]");
  p(`enabled = ${inp.conPolicyEnabled}`);
  p('branch_namespace = "clipboard"');
  p("require_pm_approval = true");
  p("require_user_instruction_for_write = true");
  p("require_librarian_policy_sources = true");
  p("require_guardian_before_external_write = true");
  p("require_external_lock = true");
  p("forbid_push_garelier_branches = true");
  p("forbid_force_push = true");
  p("forbid_blind_git_pull = true");
  p("redact_sensitive_output = true");
  p("# Remote-visible work uses these prefixes — never garelier/* (Phase 2).");
  p('allowed_external_branch_prefixes = ["publish/", "pr/", "release/"]');
  p("");
  p("[concierge_policy.required_knowledge]");
  p("paths = [");
  p('    "external_operations/external_operations_policy.md",');
  p('    "external_operations/git_remote_policy.md",');
  p('    "external_operations/promote_policy.md",');
  p('    "external_operations/rollback_policy.md",');
  p("]");

  return `${L.join("\n")}\n`;
}
